import { lstat, mkdir, realpath, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  SCAFFOLD_DEFAULT_URL,
  toolContracts,
  type ToolAnnotations,
  type ToolContract,
} from "./contracts.js";
import type { DomainDefinition } from "./domain.js";
import { handbookDomain } from "./schema.js";

/** Environment variable that moves the directory `outDir` is resolved against. */
export const SCAFFOLD_ROOT_ENV = "STRUMENTARIO_SCAFFOLD_ROOT";

/** The header agent hosts send so the change journal can attribute calls. */
const AGENT_HEADER_NAME = "X-Strumentario-Agent";
const AUTH_TOKEN_ENV = "MCP_AUTH_TOKEN";
const SERVER_NAME = "strumentario";

export type ScaffoldTarget = "client" | "host-config";

export interface ScaffoldInput {
  target: ScaffoldTarget;
  url?: string | undefined;
  auth?: boolean | undefined;
  write?: boolean | undefined;
  outDir?: string | undefined;
  overwrite?: boolean | undefined;
}

export interface ScaffoldFile {
  /** Relative to the output directory, always with forward slashes. */
  path: string;
  content: string;
}

export interface ScaffoldError {
  code: "invalid" | "exists" | "write_error";
  message: string;
  existing?: string[];
}

export interface ScaffoldResult extends Record<string, unknown> {
  ok: boolean;
  target: ScaffoldTarget;
  files: ScaffoldFile[];
  written: boolean;
  outDir?: string;
  error?: ScaffoldError;
}

export interface ScaffoldOptions {
  /** Directory `outDir` is resolved against. Defaults to $STRUMENTARIO_SCAFFOLD_ROOT, then the working directory. */
  root?: string;
  /** Contracts and domain to generate from; default to the handbook domain's. */
  contracts?: readonly ToolContract[];
  domain?: DomainDefinition;
}

// --- generation (pure, deterministic) ---------------------------------------

/** Generate the files for a target without touching the filesystem. Throws only on an invalid `url`. */
export function generateScaffoldFiles(
  input: Pick<ScaffoldInput, "target" | "url" | "auth">,
  options: Pick<ScaffoldOptions, "contracts" | "domain"> = {},
): ScaffoldFile[] {
  const contracts = options.contracts ?? toolContracts;
  const domain = options.domain ?? handbookDomain;
  return input.target === "client"
    ? [{ path: "strumentario-client.ts", content: renderClient(contracts, domain) }]
    : renderHostConfig(contracts, input.url ?? SCAFFOLD_DEFAULT_URL, input.auth === true);
}

// --- typed client -------------------------------------------------------------

interface JsonSchema {
  type?: string | string[];
  enum?: unknown[];
  const?: unknown;
  description?: string;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  additionalProperties?: boolean | JsonSchema;
  anyOf?: JsonSchema[];
}

interface EmitContext {
  /** Top-level property names whose untyped schema is emitted as this named type instead of unknown. */
  untypedAs: ReadonlyMap<string, string>;
}

function pascal(value: string): string {
  return value
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function renderClient(contracts: readonly ToolContract[], domain: DomainDefinition): string {
  // The scaffold tool generates files; it is not a page operation, so the client leaves it out.
  const tools = contracts.filter((contract) => contract.name !== "scaffold");
  const draft = `${pascal(domain.name)}Draft`;
  const key = domain.keyField;
  const context: EmitContext = { untypedAs: new Map([[domain.slots.one, draft]]) };
  const out: string[] = [];

  out.push(
    "// Generated by the Strumentario `scaffold` tool (target: client). Do not edit by hand:",
    "// regenerate it when the Strumentario schema changes. It depends on nothing, so any",
    "// MCP client with a `callTool` method (for example the official SDK `Client`) can drive it.",
    "",
    `/** The fields of a ${domain.noun} draft, as accepted by create and update. */`,
    `export interface ${draft} {`,
    ...domain.fields.map((field) => `  ${field.name}: string;`),
    "}",
    "",
  );

  for (const tool of tools) {
    const name = pascal(tool.name);
    out.push(`/** Arguments of the \`${tool.name}\` tool. */`);
    out.push(`export interface ${name}Input ${emitObject(tool.inputSchema as JsonSchema, 0, context)}`, "");
    out.push(`/** Structured result of the \`${tool.name}\` tool. */`);
    out.push(`export interface ${name}Output ${emitObject(tool.outputSchema as JsonSchema, 0, { untypedAs: new Map() })}`, "");
  }

  out.push(
    "export const TOOL_NAMES = [",
    ...tools.map((tool) => `  ${JSON.stringify(tool.name)},`),
    "] as const;",
    "",
    "export type ToolName = (typeof TOOL_NAMES)[number];",
    "",
    "/** Resource URIs served by the server. */",
    "export const RESOURCES = {",
    `  schema: ${JSON.stringify(domain.resources.schemaUri)},`,
    `  instanceTemplate: ${JSON.stringify(domain.resources.instanceTemplate)},`,
    `  journal: ${JSON.stringify(domain.resources.journalUri)},`,
    "} as const;",
    "",
    `/** URI of one ${domain.slots.one}, for reading it as a resource. */`,
    `export function ${domain.slots.one}Uri(${key}: string): string {`,
    `  return RESOURCES.instanceTemplate.replace(${JSON.stringify(`{${key}}`)}, encodeURIComponent(${key}));`,
    "}",
    "",
    "/** The part of an MCP client this module needs. The SDK `Client` satisfies it. */",
    "export interface ToolCaller {",
    "  callTool(params: {",
    "    name: string;",
    "    arguments?: Record<string, unknown>;",
    "  }): Promise<Record<string, unknown>>;",
    "}",
    "",
    "/**",
    " * Thrown when a tool call produced no structured result (the server rejected the",
    " * arguments before the tool ran). Tool-level failures such as a conflict are not thrown:",
    " * they come back as `ok: false` with an `error`.",
    " */",
    "export class ToolCallError extends Error {",
    "  constructor(",
    "    readonly tool: ToolName,",
    "    message: string,",
    "  ) {",
    "    super(message);",
    '    this.name = "ToolCallError";',
    "  }",
    "}",
    "",
    `export function createStrumentarioClient(caller: ToolCaller) {`,
    "  async function call<Output>(tool: ToolName, args: object): Promise<Output> {",
    "    const result = await caller.callTool({ name: tool, arguments: { ...args } });",
    '    const structured = result["structuredContent"];',
    '    if (typeof structured !== "object" || structured === null) {',
    "      throw new ToolCallError(",
    "        tool,",
    "        `The ${tool} tool returned no structured result. Check the arguments against its input schema (run \\`strumentario call ${tool} --help\\`).`,",
    "      );",
    "    }",
    "    return structured as Output;",
    "  }",
    "",
    "  return {",
    ...tools.map((tool) => {
      const name = pascal(tool.name);
      const required = ((tool.inputSchema as JsonSchema).required ?? []).length > 0;
      return required
        ? `    ${tool.name}: (input: ${name}Input) => call<${name}Output>(${JSON.stringify(tool.name)}, input),`
        : `    ${tool.name}: (input: ${name}Input = {}) => call<${name}Output>(${JSON.stringify(tool.name)}, input),`;
    }),
    "  };",
    "}",
    "",
    "export type StrumentarioClient = ReturnType<typeof createStrumentarioClient>;",
    "",
  );
  return out.join("\n");
}

function emitObject(schema: JsonSchema, depth: number, context: EmitContext): string {
  const properties = Object.entries(schema.properties ?? {});
  if (properties.length === 0) {
    return "Record<string, unknown>";
  }
  const pad = "  ".repeat(depth + 1);
  const required = new Set(schema.required ?? []);
  const lines = ["{"];
  for (const [name, property] of properties) {
    if (property.description) {
      lines.push(...docComment(property.description, pad));
    }
    const type = emitType(property, depth + 1, depth === 0 ? context : { untypedAs: new Map() }, depth === 0 ? name : undefined);
    lines.push(`${pad}${propertyKey(name)}${required.has(name) ? "" : "?"}: ${type};`);
  }
  lines.push(`${"  ".repeat(depth)}}`);
  return lines.join("\n");
}

function emitType(schema: JsonSchema, depth: number, context: EmitContext, topLevelName?: string): string {
  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }
  if (schema.const !== undefined) {
    return JSON.stringify(schema.const);
  }
  if (schema.anyOf) {
    return schema.anyOf.map((member) => emitType(member, depth, context)).join(" | ");
  }
  const type = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  if (type.length === 0) {
    return (topLevelName !== undefined && context.untypedAs.get(topLevelName)) || "unknown";
  }
  return type
    .map((member) => {
      switch (member) {
        case "string":
          return "string";
        case "number":
        case "integer":
          return "number";
        case "boolean":
          return "boolean";
        case "null":
          return "null";
        case "array":
          return `Array<${schema.items ? emitType(schema.items, depth, context) : "unknown"}>`;
        case "object":
          return emitObject(schema, depth, context);
        default:
          return "unknown";
      }
    })
    .join(" | ");
}

function docComment(text: string, pad: string): string[] {
  const safe = text.replace(/\*\//g, "*\\/").split("\n");
  return safe.length === 1 ? [`${pad}/** ${safe[0]} */`] : [`${pad}/**`, ...safe.map((line) => `${pad} * ${line}`), `${pad} */`];
}

function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

// --- host config ---------------------------------------------------------------

function renderHostConfig(contracts: readonly ToolContract[], url: string, auth: boolean): ScaffoldFile[] {
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== "http:" && parsed.protocol !== "https:") {
      throw new Error("not http(s)");
    }
  } catch {
    throw new ScaffoldInputError(
      `url "${url}" is not an http(s) URL. Pass the MCP endpoint, for example ${SCAFFOLD_DEFAULT_URL}.`,
    );
  }

  const headers = (agent: string, tokenRef: string): Record<string, string> => ({
    [AGENT_HEADER_NAME]: agent,
    ...(auth ? { Authorization: `Bearer ${tokenRef}` } : {}),
  });

  const cursor = {
    mcpServers: { [SERVER_NAME]: { url, headers: headers("cursor", `\${env:${AUTH_TOKEN_ENV}}`) } },
  };
  const claudeCode = {
    mcpServers: {
      [SERVER_NAME]: { type: "http", url, headers: headers("claude-code", `\${${AUTH_TOKEN_ENV}}`) },
    },
  };
  const generic = {
    name: SERVER_NAME,
    transport: "streamable-http",
    url,
    headers: headers("<your-agent-id>", `<${AUTH_TOKEN_ENV}>`),
    tools: contracts.map((contract) => ({
      name: contract.name,
      title: contract.title,
      annotations: pickAnnotations(contract.annotations),
    })),
  };

  return [
    { path: ".cursor/mcp.json", content: json(cursor) },
    { path: ".mcp.json", content: json(claudeCode) },
    { path: "strumentario.mcp.json", content: json(generic) },
  ];
}

function pickAnnotations(annotations: ToolAnnotations): ToolAnnotations {
  return Object.fromEntries(Object.entries(annotations).sort(([a], [b]) => a.localeCompare(b)));
}

function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

class ScaffoldInputError extends Error {}

// --- tool entry point: generate, and write only on request -----------------------

export async function scaffold(input: ScaffoldInput, options: ScaffoldOptions = {}): Promise<ScaffoldResult> {
  const fail = (error: ScaffoldError, files: ScaffoldFile[] = []): ScaffoldResult => ({
    ok: false,
    target: input.target,
    files,
    written: false,
    error,
  });

  let files: ScaffoldFile[];
  try {
    files = generateScaffoldFiles(input, options);
  } catch (error) {
    if (error instanceof ScaffoldInputError) {
      return fail({ code: "invalid", message: error.message });
    }
    throw error;
  }

  if (input.write !== true) {
    return { ok: true, target: input.target, files, written: false };
  }

  if (!input.outDir) {
    return fail(
      { code: "invalid", message: "write: true needs outDir, the directory to write the files into. Omit write to just return the files." },
      files,
    );
  }

  const root = path.resolve(options.root ?? process.env[SCAFFOLD_ROOT_ENV] ?? process.cwd());
  const outDir = path.resolve(root, input.outDir);
  if (!isInside(root, outDir)) {
    return fail(
      { code: "invalid", message: `outDir "${input.outDir}" is outside the scaffold root ${root}. Use a directory inside it.` },
      files,
    );
  }

  try {
    if (!(await staysInside(root, outDir))) {
      return fail(
        { code: "invalid", message: `outDir "${input.outDir}" resolves through a symbolic link to outside the scaffold root ${root}. Use a real directory inside it.` },
        files,
      );
    }

    const overwrite = input.overwrite === true;
    if (!overwrite) {
      const existing: string[] = [];
      for (const file of files) {
        if (await exists(path.join(outDir, file.path))) {
          existing.push(file.path);
        }
      }
      if (existing.length > 0) {
        return fail(refusal(existing), files);
      }
    }

    for (const file of files) {
      const target = path.join(outDir, file.path);
      await mkdir(path.dirname(target), { recursive: true });
      try {
        // "wx" fails if the file appeared since the check, so a race cannot overwrite either.
        await writeFile(target, file.content, { flag: overwrite ? "w" : "wx" });
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === "EEXIST") {
          return fail(refusal([file.path]), files);
        }
        throw error;
      }
    }
  } catch (error) {
    return fail(
      { code: "write_error", message: `Could not write to ${outDir}: ${error instanceof Error ? error.message : String(error)}. Check the directory is writable and try again.` },
      files,
    );
  }

  return { ok: true, target: input.target, files, written: true, outDir };
}

function refusal(existing: string[]): ScaffoldError {
  return {
    code: "exists",
    message: `Refusing to overwrite ${existing.join(", ")}; nothing was written. Pass overwrite: true to replace existing files, or choose another outDir.`,
    existing,
  };
}

async function exists(file: string): Promise<boolean> {
  try {
    await lstat(file);
    return true;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      return false;
    }
    throw error;
  }
}

/** The deepest existing ancestor of `target`, resolved through symlinks, must be inside the real root. */
async function staysInside(root: string, target: string): Promise<boolean> {
  let existing = target;
  while (!(await exists(existing))) {
    const parent = path.dirname(existing);
    if (parent === existing) {
      break;
    }
    existing = parent;
  }
  const realRoot = await realpath(root).catch(() => root);
  const realExisting = await realpath(existing).catch(() => existing);
  return isInside(realRoot, realExisting);
}

function isInside(root: string, target: string): boolean {
  const relative = path.relative(root, target);
  return relative !== ".." && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative);
}
