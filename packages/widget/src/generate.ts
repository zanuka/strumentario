import type { ToolContract } from "@strumentario/server";

/**
 * Generates the widget's prop and call types from the server's framework-neutral tool contracts
 * (`toolContracts`, plain JSON Schema). Nothing here knows any UI framework, and nothing restates a schema by
 * hand: change a field in `schema.ts`, run `pnpm --filter @strumentario/widget generate`, and the
 * types follow. `generated.test.ts` fails when the checked-in file no longer matches.
 */

export const WIDGET_TOOL_NAMES = ["query", "validate", "mutate"] as const;
export type WidgetToolName = (typeof WIDGET_TOOL_NAMES)[number];

/** Where the generated file lives, relative to the package root. */
export const GENERATED_PATH = "src/generated/contracts.ts";

type Schema = Record<string, unknown>;

const HEADER = `// GENERATED by packages/widget/src/generate.ts from the server's tool contracts. Do not edit.
// Regenerate with: pnpm --filter @strumentario/widget generate
`;

function asSchema(value: unknown): Schema | undefined {
  return typeof value === "object" && value !== null && !Array.isArray(value) ? (value as Schema) : undefined;
}

function comment(description: unknown, indent: string): string {
  if (typeof description !== "string" || description.trim() === "") return "";
  const text = description.replace(/\*\//g, "*\\/").trim();
  return `${indent}/** ${text} */\n`;
}

/** Renders the JSON Schema subset the contracts use (object, array, scalar, enum) as a TypeScript type. */
export function schemaToType(schema: Schema, indent = ""): string {
  const enumValues = schema["enum"];
  if (Array.isArray(enumValues)) return enumValues.map((value) => JSON.stringify(value)).join(" | ");
  switch (schema["type"]) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array": {
      const items = asSchema(schema["items"]);
      const inner = items ? schemaToType(items, indent) : "unknown";
      return /[|{]/.test(inner) ? `Array<${inner}>` : `${inner}[]`;
    }
    case "object": {
      const properties = asSchema(schema["properties"]) ?? {};
      const required = new Set(Array.isArray(schema["required"]) ? (schema["required"] as string[]) : []);
      const names = Object.keys(properties);
      if (names.length === 0) return "Record<string, unknown>";
      const inner = `${indent}  `;
      const lines = names.map((name) => {
        const property = asSchema(properties[name]) ?? {};
        const optional = required.has(name) ? "" : "?";
        return `${comment(property["description"], inner)}${inner}${name}${optional}: ${schemaToType(property, inner)};`;
      });
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default:
      // A property the contract leaves open (such as `page` on mutate) stays open.
      return "unknown";
  }
}

function pascal(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

function contractFor(contracts: readonly ToolContract[], name: string): ToolContract {
  const contract = contracts.find((candidate) => candidate.name === name);
  if (!contract) {
    throw new Error(`No "${name}" tool contract. The widget needs ${WIDGET_TOOL_NAMES.join(", ")}; check that @strumentario/server exports them in toolContracts.`);
  }
  return contract;
}

/** The stored resource (page plus revision) as the contracts describe it, taken from query's single-page output. */
function storedResource(query: ToolContract): { key: string; schema: Schema } {
  const properties = asSchema(asSchema(query.outputSchema)?.["properties"]) ?? {};
  for (const [key, value] of Object.entries(properties)) {
    const candidate = asSchema(value);
    const candidateProperties = asSchema(candidate?.["properties"]);
    if (candidate?.["type"] === "object" && candidateProperties && "revision" in candidateProperties) {
      return { key, schema: candidate };
    }
  }
  throw new Error("The query contract has no stored resource with a revision in its output. The widget edits by revision; check the server contracts.");
}

/** Builds the full text of the generated file. Pure and deterministic. */
export function generateContractsSource(contracts: readonly ToolContract[]): string {
  const query = contractFor(contracts, "query");
  const resource = storedResource(query);
  const resourceProperties = asSchema(resource.schema["properties"]) ?? {};
  const required = new Set(Array.isArray(resource.schema["required"]) ? (resource.schema["required"] as string[]) : []);
  const fields = Object.keys(resourceProperties).filter((name) => name !== "revision");

  // The key field is the one query argument that is also a resource field (slug); the others filter or limit.
  const queryArguments = Object.keys(asSchema(asSchema(query.inputSchema)?.["properties"]) ?? {});
  const keyField = queryArguments.find((name) => fields.includes(name));
  if (keyField === undefined) {
    throw new Error("The query contract has no argument that identifies one resource. The widget opens pages by key; check the server contracts.");
  }

  const out: string[] = [HEADER];

  out.push(`/** A stored page as the tools return it: the content fields plus the revision to edit against. */\nexport type StoredPage = ${schemaToType(resource.schema)};\n`);
  out.push(`/** The editable part of a page: what a draft holds and what validate and mutate take. */\nexport type PageDraft = Omit<StoredPage, "revision">;\n`);
  out.push(
    `/** The editable fields in contract order, so editors render from the schema and not from a hand-written list. */\nexport const PAGE_FIELDS = [\n${fields
      .map((name) => {
        const description = asSchema(resourceProperties[name])?.["description"];
        return `  { name: ${JSON.stringify(name)}, required: ${required.has(name)}, description: ${JSON.stringify(typeof description === "string" ? description : null)} },`;
      })
      .join("\n")}\n] as const satisfies ReadonlyArray<{ name: keyof PageDraft; required: boolean; description: string | null }>;\n`,
  );

  out.push(`/** The field that identifies one page (query's get-one argument). It is fixed once a page exists. */\nexport const KEY_FIELD = ${JSON.stringify(keyField)} as const satisfies keyof PageDraft;\n`);

  for (const name of WIDGET_TOOL_NAMES) {
    const contract = contractFor(contracts, name);
    const base = pascal(name);
    out.push(`/** Arguments of the ${name} tool. */\nexport type ${base}Input = ${schemaToType(contract.inputSchema)};\n`);
    out.push(`/** structuredContent of the ${name} tool. */\nexport type ${base}Output = ${schemaToType(contract.outputSchema)};\n`);
  }

  out.push(`export const WIDGET_TOOLS = ${JSON.stringify(WIDGET_TOOL_NAMES)} as const;\n`);
  out.push(`export type WidgetToolName = (typeof WIDGET_TOOLS)[number];\n`);
  out.push(`export interface ToolInputs {\n${WIDGET_TOOL_NAMES.map((n) => `  ${n}: ${pascal(n)}Input;`).join("\n")}\n}\n`);
  out.push(`export interface ToolOutputs {\n${WIDGET_TOOL_NAMES.map((n) => `  ${n}: ${pascal(n)}Output;`).join("\n")}\n}\n`);

  // Titles and annotations come straight from the contracts so hosts and views can show them.
  const meta = WIDGET_TOOL_NAMES.map((name) => {
    const contract = contractFor(contracts, name);
    return `  ${name}: { title: ${JSON.stringify(contract.title)}, readOnly: ${contract.annotations.readOnlyHint === true} },`;
  });
  out.push(`export const TOOL_META = {\n${meta.join("\n")}\n} as const;\n`);

  return out.join("\n");
}
